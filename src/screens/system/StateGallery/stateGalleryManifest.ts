/* ── Một định nghĩa màn thô, trước khi dựng thành `GalleryScreenEntry` ───── */

interface ScreenDef {
  readonly id: string;
  readonly name: string;
  readonly area: string;
  readonly group: ScreenGroupId;
  readonly label: string;
  /** Tên export story thật cho từng trạng thái, `null` khi màn đó thiếu. */
  readonly storyExportNames: Readonly<Record<SevenState, string | null>>;
}

function buildEntry(def: ScreenDef): GalleryScreenEntry {
  return {
    id: def.id,
    name: def.name,
    area: def.area,
    group: def.group,
    label: def.label,
    states: SEVEN_STATES.map((state) => ({
      state,
      label: SEVEN_STATE_LABELS[state],
      storyExportName: def.storyExportNames[state],
    })),
  };
}

