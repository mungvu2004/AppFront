/** Số đếm của một màn: bao nhiêu trên bảy trạng thái có story thật. */
export function screenCoverage(entry: GalleryScreenEntry): ScreenCoverage {
  const missingLabels = entry.states
    .filter((s) => s.storyExportName === null)
    .map((s) => s.label);

  return {
    screenId: entry.id,
    presentCount: entry.states.length - missingLabels.length,
    totalCount: entry.states.length,
    missingLabels,
  };
}

/** Số đếm của cả trang, gộp từ {@link screenCoverage} của từng màn. */
export function galleryCoverage(manifest: GalleryManifest): GalleryCoverage {
  const perScreen = manifest.screens.map(screenCoverage);
  const incompleteScreens = perScreen.filter((c) => c.presentCount < c.totalCount);

  return {
    presentCount: perScreen.reduce((sum, c) => sum + c.presentCount, 0),
    totalCount: perScreen.reduce((sum, c) => sum + c.totalCount, 0),
    screenCount: manifest.screens.length,
    incompleteScreens,
  };
}
