/**
 * Cổng thật.
 *
 * Giữ lịch sử đã nạp trong một biến đóng vì hợp đồng cho `restore(versionId)` đúng MỘT
 * tham số, mà phép phục hồi cần cả ảnh chụp nguồn lẫn bản đang hiện — cả hai chỉ có trong
 * danh sách. Biến ấy được đặt lại ở mỗi lượt {@link VersionHistoryGateway.listVersions},
 * nên nó là bộ nhớ tạm của lượt đọc gần nhất chứ không phải một kho song song.
 */
export function createVersionHistoryGateway(
  options: CreateVersionHistoryGatewayOptions,
): VersionHistoryGateway {
  const readNow = (): Date => options.now?.() ?? new Date();

  let history: readonly VersionHistoryEntry[] = options.entries ?? [];

  const capabilities: VersionHistoryCapabilities = {
    canShowCurrentModel3d: true,
    canHighlightEntity: true,
    canTagVersion: options.tagVersion !== undefined,
    canGroupByAuthor: false,
    canExportVersion: options.canExportVersion ?? false,
  };

  const listVersions = async (floorId: string): Promise<readonly VersionHistoryEntry[]> => {
    if (options.loadVersions !== undefined) {
      history = await options.loadVersions(floorId);
      return history;
    }

    if (options.entries === undefined) {
      throw new Error(NO_VERSION_SOURCE_REASON);
    }

    return history;
  };

  const diff = async (leftVersionId: string, rightVersionId: string): Promise<VersionDiff> => {
    const left = readFullVersion(history, leftVersionId);
    const right = readFullVersion(history, rightVersionId);
    if (left === null || right === null) {
      throw new Error(SNAPSHOT_MISSING_REASON);
    }

    return diffVersions(left.snapshot, right.snapshot);
  };

  const restore = async (versionId: string): Promise<RestoreOutcome> => {
    const source = readFullVersion(history, versionId);
    const currentEntry = history[0];
    if (source === null || currentEntry === undefined || currentEntry.kind !== 'full') {
      throw new Error(SNAPSHOT_MISSING_REASON);
    }

    const current = currentEntry.version;
    const { restoredVersion } = restoreVersion({
      floorId: options.floorId,
      newVersion: buildRestoredVersionMetadata({
        history,
        source,
        creatorId: options.creatorId,
        now: readNow,
      }),
      sourceVersion: source,
    });

    if (options.commitRestore !== undefined) {
      const outcome = await options.commitRestore({
        floorId: options.floorId,
        baseVersion: current.sequence,
        restoredVersion,
      });

      if (outcome.kind === 'conflict') {
        const resolution = resolveConflict({
          baseVersion: current.sequence,
          localChanges: toFieldChanges(diffVersions(current.snapshot, restoredVersion.snapshot)),
          remoteChanges: outcome.body.remoteChanges,
          serverVersion: outcome.body.currentVersion,
        });

        return {
          kind: 'conflict',
          conflict: toConflictNotice(
            outcome.body.remoteChanges,
            resolution.description,
            options.members,
          ),
        };
      }
    }

    const previous = history;
    history = appendVersionToHistory(history, restoredVersion);

    const undoTicket: UndoTicket = createUndoTicket({
      description: `phục hồi nội dung của phiên bản v${source.sequence}`,
      undo: () => {
        history = previous;
      },
    });

    return { kind: 'restored', restoredVersion, history, undoTicket };
  };

  const undoRestore = async (ticket: UndoTicket): Promise<readonly VersionHistoryEntry[]> => {
    ticket.undo();
    return history;
  };

  return {
    capabilities,
    listVersions,
    diff,
    restore,
    undoRestore,
    ...(options.tagVersion !== undefined ? { tagVersion: options.tagVersion } : {}),
  };
}
