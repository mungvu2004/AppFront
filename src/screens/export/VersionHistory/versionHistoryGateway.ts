/** Ảnh chụp đầy đủ của một mục lịch sử, hoặc `null` khi mục đó chỉ còn siêu dữ liệu. */
export function readFullVersion(
  history: readonly VersionHistoryEntry[],
  versionId: string,
): VersionEntry | null {
  for (const entry of history) {
    if (entry.version.id === versionId) {
      return entry.kind === 'full' ? entry.version : null;
    }
  }

  return null;
}

/**
 * Những thay đổi mà lượt phục hồi mang theo, dưới dạng `FieldChange` — đầu vào
 * `resolveConflict` đòi.
 *
 * Lấy từ chính `diffVersions`, không tự dò: chỉ các mục `kind: 'changed'` mang `field`
 * (xem `diff.ts:87-93`), và đúng bốn trường ấy khớp `FieldChange` không cần ép kiểu.
 */
export function toFieldChanges(diff: VersionDiff): FieldChange[] {
  const changes: FieldChange[] = [];

  for (const entry of diff.changed as readonly DiffEntry[]) {
    if (entry.field === undefined) {
      continue;
    }

    changes.push({
      entityId: entry.entityId,
      entityType: entry.entityType,
      field: entry.field,
      value: entry.newValue,
    });
  }

  return changes;
}

/** Số chữ cái một `Avatar` không ảnh hiện được. */
const INITIALS_LENGTH = 2;

/**
 * Chữ cái đầu của một cái tên, cho ô đại diện không ảnh.
 *
 * Chép logic của `ShareDialog/shareDialogGateway.ts:150` thay vì nhập nó về: file kia kéo
 * theo `@/api/appClient` và `@/store`, và một `import` từ đây sẽ lôi cả hai vào phần gói
 * của tuyến lịch sử phiên bản — cổng kích thước gói đo theo TỪNG tuyến. Bảy dòng thuần
 * rẻ hơn một phụ thuộc chéo màn.
 *
 * Không có chữ nào đọc được thì trả chuỗi rỗng, và view vẽ ô trống thay vì một dấu hỏi
 * giả vờ là tên.
 */
export function initialsOf(name: string): string {
  const words = name.trim().split(/\s+/u).filter((word) => word.length > 0);
  if (words.length === 0) {
    return '';
  }

  const first = words[0] ?? '';
  const last = words[words.length - 1] ?? '';
  const letters = words.length === 1 ? first.slice(0, 1) : `${first.slice(0, 1)}${last.slice(0, 1)}`;

  return letters.slice(0, INITIALS_LENGTH).toLocaleUpperCase('vi-VN');
}

/** `changedBy` sang tên hiển thị; lùi về chính chuỗi thô khi không tra được. */
export function readActorName(
  changedBy: string,
  members: readonly VersionActor[] | undefined,
): string {
  return members?.find((member) => member.id === changedBy)?.name ?? changedBy;
}

/**
 * Thân 409 thành câu người đọc hiểu.
 *
 * `message` nêu AI đã sửa; `detail` là `ConflictResolution.description` do
 * `resolveConflict` sinh (`conflict.ts:76,88`) — màn không tự đếm và không tự kể lại nội
 * dung thay đổi từ xa. Không có trường nào cho phép ghi đè, và đó là chủ ý.
 */
export function toConflictNotice(
  remoteChanges: readonly RemoteFieldChange[],
  description: string,
  members: readonly VersionActor[] | undefined,
): ConflictNoticeModel {
  const first = remoteChanges[0];
  const actorName = first === undefined ? 'người khác' : readActorName(first.changedBy, members);
  const changedOn = first === undefined ? null : formatCalendarDate(new Date(first.changedAt));

  return {
    actorName,
    message:
      changedOn === null
        ? `${actorName} đã sửa bản vẽ này từ lúc bạn mở trang, nên lượt phục hồi chưa được ghi.`
        : `${actorName} đã sửa bản vẽ này ngày ${changedOn}, sau lúc bạn mở trang, nên lượt phục hồi chưa được ghi.`,
    detail: description.length === 0 ? null : description,
    dismissLabel: 'đã hiểu',
  };
}

/**
 * Siêu dữ liệu của phiên bản MỚI mà lượt phục hồi sinh ra — mục 3 của bản kê nợ.
 *
 * `sequence` là số lớn nhất đang có cộng một, đúng thứ test `diff.test.ts:286-313` chờ
 * đợi (đang ở v15, phục hồi v14, sinh ra v16). Đếm phiên bản vì thế **tăng thêm một**,
 * không bao giờ giảm.
 */
export function buildRestoredVersionMetadata(input: {
  readonly history: readonly VersionHistoryEntry[];
  readonly source: VersionEntry;
  readonly creatorId: string;
  readonly now: () => Date;
}): VersionMetadata {
  let highest = input.source.sequence;
  for (const entry of input.history) {
    if (entry.version.sequence > highest) {
      highest = entry.version.sequence;
    }
  }

  return {
    createdAt: input.now().toISOString(),
    creatorId: input.creatorId,
    id: createUuid(),
    note: `phục hồi nội dung của phiên bản v${input.source.sequence}`,
    sequence: highest + 1,
  };
}

