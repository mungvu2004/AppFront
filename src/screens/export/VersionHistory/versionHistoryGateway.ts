/** Một người có thể xuất hiện trong `changedBy` của thân 409. */
export interface VersionActor {
  readonly id: string;
  readonly name: string;
}

/** Thân 409 khi lượt ghi phục hồi bị máy chủ từ chối vì đã cũ. */
export interface CommitRestoreConflict {
  readonly kind: 'conflict';
  readonly body: ConflictResponseBody;
}

/** Lượt ghi phục hồi đã được máy chủ nhận. */
export interface CommitRestoreAccepted {
  readonly kind: 'accepted';
}

export type CommitRestoreResult = CommitRestoreAccepted | CommitRestoreConflict;

/** Thứ một lượt ghi phục hồi cần biết. `baseVersion` là `sequence` của bản đang hiện. */
export interface CommitRestoreInput {
  readonly floorId: string;
  readonly baseVersion: number;
  readonly restoredVersion: VersionEntry;
}

export interface CreateVersionHistoryGatewayOptions {
  /** Tầng mà lịch sử này thuộc về — `restoreVersion` đòi nó, xem `restore.ts:50`. */
  readonly floorId: string;
  /** Ai đang phục hồi. Đi thẳng vào `VersionMetadata.creatorId`; không có bộ tra nào khác. */
  readonly creatorId: string;
  /** Lịch sử bơm sẵn — dùng khi chưa có bộ nạp (xem mục 1 của bản kê nợ). */
  readonly entries?: readonly VersionHistoryEntry[];
  /** Bộ nạp thật, ngày endpoint liệt kê tồn tại. Phải tự đi qua `src/lib/http`. */
  readonly loadVersions?: (floorId: string) => Promise<readonly VersionHistoryEntry[]>;
  /** Lượt ghi phục hồi ra máy chủ. Không bơm ⇒ phục hồi chạy tại chỗ, không có 409. */
  readonly commitRestore?: (input: CommitRestoreInput) => Promise<CommitRestoreResult>;
  /** Danh sách thành viên để tra `changedBy` sang tên hiển thị. Không có ⇒ giữ chuỗi thô. */
  readonly members?: readonly VersionActor[];
  /** Đường gắn nhãn, nếu nơi ráp có. Không bơm ⇒ `canTagVersion` là `false`. */
  readonly tagVersion?: (versionId: string, label: string) => Promise<VersionMetadata>;
  /** Nơi ráp có sẵn đường xuất một phiên bản hay không. Mặc định `false` — NOT FOUND. */
  readonly canExportVersion?: boolean;
  /** Đồng hồ. Bơm được để test không phụ thuộc giờ máy. */
  readonly now?: () => Date;
}

